import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _strip():
    spec = importlib.util.spec_from_file_location("pr_footer", ROOT / ".github" / "scripts" / "pr_footer.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.strip_footer


def test_removes_the_generated_footer_and_session_link():
    body = ("## Summary\n\nFix the thing.\n\n- [x] tests\n\n"
            "🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\n"
            "https://claude.ai/code/session_0123abc\n")
    assert _strip()(body) == "## Summary\n\nFix the thing.\n\n- [x] tests\n"


def test_removes_a_rule_above_the_footer_and_handles_crlf():
    body = "Text.\r\n\r\n---\r\n\r\n_Generated by [Claude Code](https://claude.ai/code)_\r\n"
    assert _strip()(body) == "Text.\n"


def test_leaves_other_descriptions_alone():
    strip = _strip()
    for body in ["", None, "Plain text.\n", "Mentions Claude Code in the middle.\n\nEnd.\n",
                 "Link https://claude.ai/code/session_x inside a sentence.\n"]:
        assert strip(body) == body
